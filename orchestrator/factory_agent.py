import os
import sys
import re
from llm_router import call_llm

def main():
    if len(sys.argv) < 2:
        print("No idea provided. Usage: python factory_agent.py 'color picker'")
        return
        
    idea = " ".join(sys.argv[1:])
    tool_name = idea.lower().replace(" ", "-")
    filename = f"{tool_name}.html"
    
    system_prompt = "You are an expert web developer. Generate a complete, single-file HTML page (with inline CSS and JS) for the requested tool. Make it look modern and beautiful. Return ONLY the raw HTML code."
    user_prompt = f"Create a tool for: {idea}"
    
    print(f"Building tool: {idea}...")
    html_code, provider = call_llm(system_prompt, user_prompt, json_mode=False)
    
    if not html_code:
        print("Failed to generate HTML.")
        return
        
    # Save the tool
    os.makedirs("../tools", exist_ok=True)
    with open(f"../tools/{filename}", "w", encoding="utf-8") as f:
        f.write(html_code)
        
    # Update index.html (Inject card)
    index_path = "../index.html"
    with open(index_path, "r", encoding="utf-8") as f:
        index_content = f.read()
        
    card_html = f'''
        <a href="tools/{filename}" class="card">
            <h2>{idea.title()}</h2>
            <p>Generated by AI</p>
        </a>
    '''
    
    index_content = index_content.replace('<!-- Cards will be injected here -->', card_html + '\n        <!-- Cards will be injected here -->')
    
    with open(index_path, "w", encoding="utf-8") as f:
        f.write(index_content)
        
    print(f"Tool {filename} created and injected into index.html using {provider}.")

if __name__ == "__main__":
    main()
